// Helpers for scan.mjs: size walk (cached), memory-note summaries, PROJECT.md card, MOC table.
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { opendir, lstat } from 'node:fs/promises';
import { join, basename } from 'node:path';
import { DEP_DIRS } from '../lib/paths.mjs';
import { parseFrontmatter } from '../lib/frontmatter.mjs';

// ---- size walk: per-folder cache keyed on the folder mtime + newest top-level child mtime ----
export function loadSizeCache(file) {
  try { return JSON.parse(readFileSync(file, 'utf8')); } catch { return {}; }
}
export function saveSizeCache(file, cache) {
  writeFileSync(file, JSON.stringify(cache, null, 1));
}

function sizeKey(root) {
  let newest = statSync(root).mtimeMs;
  for (const e of readdirSync(root, { withFileTypes: true })) {
    if (DEP_DIRS.has(e.name) || e.name === '.git') continue;
    try { newest = Math.max(newest, statSync(join(root, e.name)).mtimeMs); } catch { /* locked */ }
  }
  return String(Math.round(newest));
}

// --no-size: reuse whatever the last full walk stored; null when nothing is cached.
export function cachedSize(root, cache) {
  const e = cache?.[root];
  return e?.size ? { code: e.size.code, deps: e.size.deps, at: e.at ?? null } : null;
}

export async function dirSize(root, cache) {
  const key = sizeKey(root);
  if (cache[root]?.key === key) return cache[root].size;
  let code = 0, deps = 0;
  async function walk(dir, inDeps) {
    let handle;
    try { handle = await opendir(dir); } catch { return; }
    for await (const ent of handle) {
      const full = join(dir, ent.name);
      if (ent.isSymbolicLink()) continue; // never follow junctions/links
      if (ent.isDirectory()) await walk(full, inDeps || DEP_DIRS.has(ent.name) || ent.name === '.git');
      else if (ent.isFile()) {
        try { const { size } = await lstat(full); if (inDeps) deps += size; else code += size; } catch { /* locked */ }
      }
    }
  }
  await walk(root, false);
  cache[root] = { key, size: { code, deps }, at: new Date().toISOString() };
  return cache[root].size;
}

// ---- memory notes ----
export function memoryNotes(files) {
  const notes = [];
  for (const file of files ?? []) {
    if (!existsSync(file)) { notes.push({ name: basename(file), description: 'file missing', missing: true, file, mtime: '' }); continue; }
    try {
      const text = readFileSync(file, 'utf8');
      const { data, body } = parseFrontmatter(text);
      const heading = body.match(/^#\s+(.+)$/m)?.[1];
      const firstLine = body.split('\n').map((l) => l.trim()).find((l) => l && !l.startsWith('#'));
      notes.push({
        name: data.name ?? heading ?? basename(file).replace(/\.md$/, ''),
        description: data.description ?? firstLine?.slice(0, 200) ?? '',
        type: data.type ?? data.metadata?.type ?? null,
        file, mtime: statSync(file).mtime.toISOString(),
      });
    } catch { /* unreadable */ }
  }
  return notes.sort((a, b) => b.mtime.localeCompare(a.mtime));
}

// ---- PROJECT.md card in the project home (overrides name, family, status, purpose, uses) ----
export function readCard(home) {
  const file = join(home, 'PROJECT.md');
  if (!existsSync(file)) return null;
  try { return { file: file.replaceAll('\\', '/'), data: parseFrontmatter(readFileSync(file, 'utf8')).data }; } catch { return null; }
}

// ---- MOC status table between <!-- dashboard:start/end --> markers ----
const ORDER = { active: 0, undecided: 1, parked: 2, archived: 3, terminated: 4 };

export function mocTable(projects, now = new Date()) {
  const rows = [...projects]
    .sort((a, b) => (ORDER[a.status] ?? 9) - (ORDER[b.status] ?? 9) || a.group.localeCompare(b.group) || a.name.localeCompare(b.name))
    .map((p) => {
      const g = p.repos[0]?.git?.value;
      const gitCell = g
        ? [g.branch, g.localOnlyCommits ? `${g.localOnlyCommits} unpushed` : '', g.modified ? `${g.modified} modified` : '', g.untracked ? `${g.untracked} untracked` : ''].filter(Boolean).join(', ')
        : (p.repos.length ? 'git unknown' : (p.exists ? 'no git' : 'folder missing'));
      return `| [[${p.noteId}\\|${p.name}]] | ${p.status} | ${p.group} | ${p.summary.replace(/\|/g, '/')} | \`${p.path}\` | ${gitCell} | ${p.blockers.length} |`;
    });
  return [
    '<!-- dashboard:start — generated by Overmap scan.mjs; edit the project notes, not this table -->',
    `_Scanned ${now.toISOString().slice(0, 16).replace('T', ' ')} · ${projects.length} projects. Status and blockers come from each project note's frontmatter / "## Blockers"._`,
    '',
    '| Project | Status | Group | Purpose | Path | Git | Open blockers |',
    '|---------|--------|-------|---------|------|-----|---------------|',
    ...rows,
    '<!-- dashboard:end -->',
  ].join('\n');
}

// Writes the table into the MOC. Never creates the file. Returns true when written.
export function updateMoc(mocFile, table) {
  if (!mocFile || !existsSync(mocFile)) return false;
  let moc = readFileSync(mocFile, 'utf8');
  const marked = /<!-- dashboard:start[\s\S]*?<!-- dashboard:end -->/;
  const heading = /(## Status at a Glance\s*\r?\n)[\s\S]*?(?=\r?\n---)/;
  if (marked.test(moc)) moc = moc.replace(marked, () => table);
  else if (heading.test(moc)) moc = moc.replace(heading, (_, h) => `${h}\n${table}\n`);
  else return false;
  const stamp = (t) => t.replace(/^_Scanned .*$/m, '');
  const old = readFileSync(mocFile, 'utf8');
  if (stamp(old) !== stamp(moc)) writeFileSync(mocFile, moc);
  return true;
}

// Writes only when the content changed (ignoring the timestamp line). Returns true when written.
export function writeIfChanged(file, content) {
  const stamp = (t) => t.replace(/^_?(Scanned|Generated).*$/gm, '');
  try { if (stamp(readFileSync(file, 'utf8')) === stamp(content)) return false; } catch { /* new file */ }
  writeFileSync(file, content);
  return true;
}

// Writes the architecture file when one is configured. Returns 'written', 'unchanged' or 'not-configured'
// (a null or empty config.architectureFile writes nothing: no file named "null" in the working folder).
export function writeArchitectureFile(file, content) {
  if (typeof file !== 'string' || file === '') return 'not-configured';
  return writeIfChanged(file, content) ? 'written' : 'unchanged';
}
