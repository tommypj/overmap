import { test } from 'node:test';
import assert from 'node:assert/strict';
import { writeArchitecture } from '../scan/architecture.mjs';

const entry = (id, name, family, extra = {}) => ({
  id, name, family, kind: 'project', home: `/projects/${id}`, repos: [`/projects/${id}`],
  worktreesManaged: [], oldPaths: [], uses: [], ...extra,
});
const registry = new Map([
  ['b', entry('b', 'Beta', 'Zed', { uses: ['neon'], oldPaths: ['/old/b'] })],
  ['a', entry('a', 'Alpha', 'Acme')],
]);
const projects = [
  { id: 'a', status: 'active', card: '/projects/a/PROJECT.md', repos: [{ path: '/projects/a', git: { at: 'x', value: { branch: 'main', worktrees: [{ path: '/projects/a-wt', branch: 'feat/x' }] } } }], plan: { at: 'x', value: { percent: 40 } } },
  { id: 'b', status: 'parked', card: null, repos: [], plan: { at: 'x', value: null } },
];
const config = { vaultProjectsDir: '/vault/Projects' };

test('marker, rules, one H2 per project sorted by family then name, details', () => {
  const out = writeArchitecture(projects, registry, config);
  assert.ok(out.startsWith('<!-- generated by Overmap scan.mjs; do not edit -->'));
  assert.equal(out.split('\n').filter((l) => l.startsWith('## ')).length, 2);
  assert.ok(out.includes("update the project's plan before you stop"));
  assert.ok(out.includes('/projects/a'));
  assert.ok(out.includes('/vault'));
  assert.ok(out.includes('/old/b'));
  assert.ok(out.includes('neon'));
  assert.ok(out.includes('40%'));
  assert.ok(out.includes('`/projects/a` (main)'));
  assert.ok(out.includes('`/projects/a-wt` (feat/x)'));
  assert.equal(out.includes('Unmapped'), false);
  assert.ok(out.includes('# Plan format') && out.includes('- [~]'));
  assert.ok(out.indexOf('## Alpha') < out.indexOf('## Beta'));
});

test('repos line: detached and unknown; resolved project fields win over the registry', () => {
  const ps = [{ id: 'a', status: 'active', name: 'Renamed', group: 'Zzz', uses: ['stripe'], repos: [{ path: '/projects/a', git: { at: 'x', value: { branch: null, worktrees: [] } } }] },
    { id: 'b', status: 'active', repos: [{ path: '/projects/b', git: { at: 'x', error: 'boom' } }] }];
  const reg = new Map(registry);
  reg.get('b').repos = ['/projects/b'];
  const out = writeArchitecture(ps, reg, config, []);
  assert.ok(out.includes('`/projects/a` (detached)'));
  assert.ok(out.includes('`/projects/b` (unknown)'));
  assert.ok(out.includes('## Renamed') && out.includes('family: Zzz') && out.includes('uses: stripe'));
});
